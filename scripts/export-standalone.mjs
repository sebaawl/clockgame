import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const built = await readFile(new URL('dist/index.html', root), 'utf8');
const html = '<!-- Generated by npm run build. Edit src/index.html and src/ instead. -->\n' + built;
await writeFile(new URL('dist/index.html', root), html);
await writeFile(new URL('index.html', root), html);
console.log('Portable index.html generated: open directly in a browser, including offline.');
