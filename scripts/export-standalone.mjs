import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const built = await readFile(new URL('dist/index.html', root), 'utf8');
const license = await readFile(new URL('node_modules/@fontsource/poppins/LICENSE', root), 'utf8');
const fontLicense = `<script type="application/json" id="font-license">${JSON.stringify({ font: 'Poppins', license }).replaceAll('<', '\\u003c')}</script>`;
const html = '<!-- Generated by npm run build. Edit src/index.html and src/ instead. -->\n' + built.replace('</head>', `${fontLicense}\n</head>`);
await writeFile(new URL('dist/index.html', root), html);
await writeFile(new URL('index.html', root), html);
console.log('Portable index.html generated with embedded Poppins and its license.');
