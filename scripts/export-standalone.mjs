import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const built = await readFile(new URL('dist/index.html', root), 'utf8');
const licenses = await Promise.all(['dm-sans', 'instrument-serif'].map(async (font) => ({
  font,
  license: await readFile(new URL(`node_modules/@fontsource/${font}/LICENSE`, root), 'utf8'),
})));

// Keep the fonts' full license text with the portable file, even when copied alone.
const fontLicenses = `<script type="application/json" id="font-licenses">${JSON.stringify(licenses).replaceAll('<', '\\u003c')}</script>`;
const standalone = built.replace('</head>', `${fontLicenses}\n</head>`);
const html = '<!-- Generated by npm run build. Edit src/index.html and src/ instead. -->\n' + standalone;
await writeFile(new URL('dist/index.html', root), html);
await writeFile(new URL('index.html', root), html);
console.log('Portable index.html generated: open directly in a browser, including offline.');
